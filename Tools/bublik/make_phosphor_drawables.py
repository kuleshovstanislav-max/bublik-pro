HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Tools/bublik/make_phosphor_drawables.py from Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{w}"
    android:viewportHeight="{h}">
"""


def fetch(names):
    url = "https://api.iconify.design/ph.json?icons=" + ",".join(names)
    raw = subprocess.run(["curl", "-sf", "--max-time", "60", url], check=True, capture_output=True, text=True).stdout
    return json.loads(raw)


def paths(body):
    for tag in re.findall(r"<path\b[^>]*>", body):
        d = re.search(r'\sd="([^"]+)"', tag).group(1)
        opacity = re.search(r'\sopacity="([^"]+)"', tag)
        yield d, float(opacity.group(1)) if opacity else 1.0


def write_override(res_dir, name, body, canvas_dp, glyph_dp):
    view = 256 * canvas_dp / glyph_dp
    shift = (view - 256) / 2
    xml = (HEADER.replace('android:width="24dp"', f'android:width="{canvas_dp}dp"')
           .replace('android:height="24dp"', f'android:height="{canvas_dp}dp"')
           .format(w=f"{view:g}", h=f"{view:g}"))
    xml += f'    <group android:translateX="{shift:g}" android:translateY="{shift:g}">\n'
    for d, alpha in paths(body):
        alpha_attr = f'\n            android:fillAlpha="{alpha:g}"' if alpha < 1 else ""
        xml += f'        <path\n            android:fillColor="#FFFFFFFF"{alpha_attr}\n            android:pathData="{d}" />\n'
    xml += "    </group>\n</vector>\n"
    open(f"{res_dir}/{name}.xml", "w", encoding="utf-8").write(xml)
    print(f"override {name}")


def main(out_dir, override_dir=None):
    names = [f"{ph}-{style}" for ph in ICONS.values() for style in ("duotone", "fill")]
    data = fetch(names)
    w, h = data.get("width", 256), data.get("height", 256)
    for key, ph in ICONS.items():
        for style in ("duotone", "fill"):
            body = data["icons"][f"{ph}-{style}"]["body"]
            xml = HEADER.format(w=w, h=h)
            for d, alpha in paths(body):
                alpha_attr = f'\n        android:fillAlpha="{alpha:g}"' if alpha < 1 else ""
                xml += f'    <path\n        android:fillColor="#FFFFFFFF"{alpha_attr}\n        android:pathData="{d}" />\n'
            xml += "</vector>\n"
            name = f"bublik_ph_{key}_{style}.xml"
            open(f"{out_dir}/{name}", "w", encoding="utf-8").write(xml)
            print(name)
    if override_dir:
        wanted = sorted({f"{ph}-{style}" for ph, style, _, _ in OVERRIDES.values()})
        icons = fetch(wanted)["icons"]
        for name, (ph, style, canvas_dp, glyph_dp) in OVERRIDES.items():
            write_override(override_dir, name, icons[f"{ph}-{style}"]["body"], canvas_dp, glyph_dp)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
